assign = {(c, h): model.new_bool_var(f"{c}_{h}") for c in concerts for h in halls
          if data["requirement"][c] <= data["capacity"][h]
          }
horizon = 300
# start ={(c,h):model.new_int_var(0,horizon-(data["end"][c]-data["start"][c]), f"st_{c}_{h}") for (c,h),v in assign.items()}
start = {(c, h): data["start"][c] for (c, h), v in assign.items()}
start_interval = {(c, h): model.new_optional_fixed_size_interval_var(start[c, h], data["end"][c] - data["start"][c], v,
                                                                     f"st_interval_{c}_{h}") for (c, h), v in
                  assign.items()}

for h in halls:
    expr_intervals = [start_interval[c, h] for (c, hh), v in assign.items() if h == hh]
    model.add_no_overlap(expr_intervals)

for c in concerts:
    expr = [assign.get((c, h), 0) for h in halls]
    model.add_at_most_one(expr)

of = [v * data["price"][c] for (c, h), v in assign.items()]
model.maximize(sum(of))
stat = solver.solve(model)
print(solver.status_name(stat), solver.objective_value)

out = {c: sum(solver.value(assign.get((c, h), 0)) for h in halls) for c in concerts}
